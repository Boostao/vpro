package reportcore

import (
	"strings"
	"testing"
)

func TestRenderQuartoHTMLReportStructurePrintCSSAndEscaping(t *testing.T) {
	res, err := RenderQuartoHTMLReport(HTMLReportDocument{
		Title:       "CWHvm1 <Vegetation> Summary",
		Subtitle:    "Presence & Mean Cover",
		ReportKind:  "Summary Vegetation",
		Project:     "Sample",
		SU:          "None",
		ScopeLabel:  "All Project Plots (fallback)",
		GeneratedAt: "2026-11-26 14:00",
		UnitCount:   2,
		PlotCount:   12,
		Notice:      "No Site Unit table was selected; showing all plots grouped automatically.",
		Badges: []HTMLReportBadge{
			{Label: "Grouping", Value: "Layer"},
		},
		Tables: []HTMLReportTable{
			{
				Title:       "Vegetation Summary Table",
				PlotCount:   12,
				Headers:     []string{"Layer", "Species", "CWHvm1/01 (n=7)", "CWHvm1/05 (n=5)"},
				NumericCols: []bool{false, false, true, true},
				Rows: []HTMLReportRow{
					{Cells: []string{"TREE LAYER"}, IsHeading: true},
					{Cells: []string{"A1", "TSUGHET", "100 / 42.5", "80 / 28.0"}},
					{Cells: []string{"Total", "2 species", "42.5", "28.0"}, IsSummary: true},
				},
				Footnote: "Values shown as Presence (%) / Mean Cover (%).",
			},
		},
		Footnotes: []string{"Generated by VPro 2.0"},
	})
	if err != nil {
		t.Fatalf("RenderQuartoHTMLReport: %v", err)
	}
	if res.UnitCount != 2 || res.PlotCount != 12 || res.TableCount != 1 {
		t.Fatalf("unexpected counts: %+v", res)
	}
	for _, needle := range []string{
		"<!DOCTYPE html>",
		"#003366",
		"#fcba19",
		"@media print",
		"CWHvm1 &lt;Vegetation&gt; Summary",
		"All Project Plots (fallback)",
		"n = 12",
		`class="group-row"`,
		`class="summary-row"`,
		`class="num"`,
		"TSUGHET",
		"Generated by VPro 2.0",
	} {
		if !strings.Contains(res.HTML, needle) {
			t.Fatalf("expected rendered HTML to contain %q", needle)
		}
	}
	if strings.Contains(res.HTML, "<Vegetation>") {
		t.Fatal("unescaped HTML tag leaked into output")
	}
}

func TestRenderQuartoHTMLReportRequiresTitle(t *testing.T) {
	if _, err := RenderQuartoHTMLReport(HTMLReportDocument{}); err == nil {
		t.Fatal("expected error when both Title and ReportKind are empty")
	}
}
